"""
Turn landmark PNGs into the pixel-grid sprites the game uses.

Usage (from the mbta-game folder):
    pip install pillow
    python scripts/png_to_sprite.py path/to/png/folder [width] [colors]

    width  = sprite width in pixels (default 24, matches the existing landmarks)
    colors = max colours per sprite (default 12)

Writes src/data/generatedSprites.js
"""
import sys
from pathlib import Path
from PIL import Image

# PNG file name (lowercase, letters+digits only)  ->  landmark id in moreLandmarks.js
FILE_TO_ID = {
    "bucastle": "bu-castle",
    "isabellastewartgardner": "gardner-museum",
    "symphonyhall": "symphony-hall",
    "bostoncommon": "boston-common",
    "bostonafricanamericannationalhistoric": "baahm",
    "paulrevere": "paul-revere-house",
    "freedomtrail": "freedom-trail",
    "esplanadetrail": "esplanade",
        "bostonpubliclibrary": "bpl",
    "fenwaypark": "fenway-park",
    "mfa": "mfa",
    "museumofscience": "museum-of-science",
    "prudential": "prudential",
    "statehouse": "state-house",
    "tdgarden": "td-garden",
}
CHARS = "ABCDEFGHIJLMNOPQRSTUVWXYZ"  # no K (outline ink) and no '.' (transparent)


def load_sprite(path, width, ncolors):
    img = Image.open(path).convert("RGBA")

    # No real transparency? Treat anything close to the corner colour as background.
    if img.getchannel("A").getextrema()[0] == 255:
        bg = img.getpixel((0, 0))[:3]
        px = img.load()
        for y in range(img.height):
            for x in range(img.width):
                r, g, b, _ = px[x, y]
                if abs(r - bg[0]) + abs(g - bg[1]) + abs(b - bg[2]) < 40:
                    px[x, y] = (0, 0, 0, 0)

    bbox = img.getchannel("A").point(lambda a: 255 if a > 20 else 0).getbbox()
    if bbox:
        img = img.crop(bbox)

    height = max(1, round(img.height * width / img.width))
    img = img.resize((width, height), Image.LANCZOS)

    alpha = img.getchannel("A").point(lambda a: 255 if a > 110 else 0)
    flat = Image.new("RGB", img.size, (0, 0, 0))
    flat.paste(img.convert("RGB"), mask=alpha)
    q = flat.quantize(colors=ncolors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()

    opaque = [[alpha.getpixel((x, y)) > 0 for x in range(width)] for y in range(height)]
    index_char, colors, rows = {}, {}, []

    for y in range(height):
        row = ""
        for x in range(width):
            if opaque[y][x]:
                i = q.getpixel((x, y))
                if i not in index_char:
                    ch = CHARS[len(index_char) % len(CHARS)]
                    index_char[i] = ch
                    r, g, b = pal[i * 3 : i * 3 + 3]
                    colors[ch] = "#%02x%02x%02x" % (r, g, b)
                row += index_char[i]
            else:
                near = any(
                    0 <= y + dy < height and 0 <= x + dx < width and opaque[y + dy][x + dx]
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))
                )
                row += "K" if near else "."
        rows.append(row)
    return rows, colors


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    folder = Path(sys.argv[1])
    width = int(sys.argv[2]) if len(sys.argv) > 2 else 24
    ncolors = int(sys.argv[3]) if len(sys.argv) > 3 else 12

    out = {}
    for f in sorted(folder.glob("*.png")):
        key = "".join(c for c in f.stem.lower() if c.isalnum())
        lid = FILE_TO_ID.get(key)
        if not lid:
            print(f"skip   {f.name} (not in FILE_TO_ID)")
            continue
        out[lid] = load_sprite(f, width, ncolors)
        print(f"ok     {f.name} -> {lid} ({len(out[lid][0][0])}x{len(out[lid][0])})")

    lines = [
        "// AUTO-GENERATED by scripts/png_to_sprite.py. Re-run the script instead of editing.",
        "import { PALETTE } from '../theme/pixel';",
        "",
        "export const generatedSprites = {",
    ]
    for lid, (rows, colors) in out.items():
        lines.append(f"  '{lid}': {{")
        lines.append("    rows: [")
        lines += [f"      '{r}'," for r in rows]
        lines.append("    ],")
        cs = ", ".join(f"{k}: '{v}'" for k, v in colors.items())
        lines.append(f"    colors: {{ K: PALETTE.ink, {cs} }},")
        lines.append("  },")
    lines.append("};")
    dest = Path("src/data/generatedSprites.js")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nWrote {dest} with {len(out)} sprites")


main()
